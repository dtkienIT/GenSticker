import type { ApiErrorCode } from '@/services/contracts/types';

import { localized, type LocalizedString } from './types';

export interface LocalizedErrorStrings {
  readonly title: LocalizedString;
  readonly message: LocalizedString;
  readonly action: LocalizedString;
}

function errorStrings(
  titleVi: string,
  messageVi: string,
  actionVi: string,
  titleEn: string,
  messageEn: string,
  actionEn: string,
): LocalizedErrorStrings {
  return Object.freeze({
    title: localized(titleVi, titleEn),
    message: localized(messageVi, messageEn),
    action: localized(actionVi, actionEn),
  });
}

